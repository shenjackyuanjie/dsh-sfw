const GLYPH_WIDTH = 5
const GLYPH_HEIGHT = 7
const GLYPH_ADVANCE = 6

/** 把一个位图字符转换为由单位方块组成的单条 SVG path。 */
function glyphPath(rows: readonly string[], offsetX: number): string {
  let path = ''
  for (let row = 0; row < GLYPH_HEIGHT; row++) {
    for (let column = 0; column < GLYPH_WIDTH; column++) {
      if (rows[row]?.[column] !== '1') continue
      path += `M${offsetX + column} ${row}h1v1h-1Z`
    }
  }
  return path
}

/** 把任意名称转换为无需字体的像素矢量字标。 */
function createPixelWordmark(value: string): WordmarkVector {
  const characters = [...value.toUpperCase()]
  const split = Math.ceil(characters.length / 2)
  const paths: WordmarkPath[] = []
  for (const [index, character] of characters.entries()) {
    const rows = PIXEL_FONT[character] ?? PIXEL_FONT['?']!
    const d = glyphPath(rows, index * GLYPH_ADVANCE)
    if (d !== '') paths.push({ d, opacity: index < split ? 0.72 : 1 })
  }
  const width = Math.max(GLYPH_WIDTH, characters.length * GLYPH_ADVANCE - 1)
  return {
    key: value.toLowerCase(),
    viewBox: `0 0 ${width} ${GLYPH_HEIGHT}`,
    paths,
  }
}

/**
 * 解析一个配置名称。OpenCode 走官方几何，其余名称走通用像素矢量字库。
 * @param value 已经过配置边界校验的非空名称。
 */
export function resolveWordmark(value: string): WordmarkVector {
  const normalized = value.trim()
  if (normalized.toLowerCase() === OPENCODE.key) return OPENCODE
  return createPixelWordmark(normalized)
}
